export function spellById(id: string): SpellDef {
  const s = SPELLS.find((x) => x.id === id);
  if (!s) throw new Error(`Unknown spell: ${id}`);
  return s;
}

export function spellsForClass(classId: string, level?: 0 | 1 | 2): SpellDef[] {
  return SPELLS.filter((s) => s.classes.includes(classId as never) && (level === undefined || s.level === level));
}
